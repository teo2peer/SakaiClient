import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = dirname(require.resolve('pdfjs-dist/package.json'));
const assets = {};
for (const directory of ['cmaps', 'standard_fonts', 'wasm', 'iccs']) {
  for (const name of await readdir(join(root, directory))) {
    if (!/\.(bcmap|ttf|pfb|wasm|icc)$/.test(name)) continue;
    assets[name] = (await readFile(join(root, directory, name))).toString('base64');
  }
}
await writeFile(fileURLToPath(new URL('../src/lib/pdf-assets.generated.ts', import.meta.url)),
  `// Generated by scripts/generate-pdf-assets.mjs. Do not edit.\nconst assets: Record<string, string> = ${JSON.stringify(assets)};\nexport default assets;\n`);
console.info(`Bundled ${Object.keys(assets).length} local PDF support assets.`);
